/**
 * Generates a substring of a given string between the bounds i and j
 * @param str   The string to get a subset of
 * @param i     The start offset of the substring
 * @param j     The end offset of the substr
 * @return      The substring generated by this method
 */
char* substring (int i, int j, const char* str)
{
    // get the length of the strgin
    int len = length(str);
    // make sure i and j are within bounds
    if(i < 0 || j > len || i >= j)
    {
        return nullptr;
    }
    
    // ignore the first i characters
    for(int c = 0; c < i; c++)
    {
        str++;
    }

    // figure out how long the character array needs to be
    const int subStrLen = j - i;
    
    // declare and initialise said array
    char* out = new char[subStrLen + 1];

    // populate it
    for(int c = 0; c < subStrLen; c++)
    {
        out[c] = *str++;
    }

    // add the terminator
    out [subStrLen] = '\0';

    // return it
    return out;
}

