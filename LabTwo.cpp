/**
 * A function to determine the length of a string in bytes, where a c++ string is a char array type pointer that ends with \0
 * @param str   the string chararray to be used
 * @returns The length of the string
 */
unsigned int length(const char* str)
{
    // assume length 0
    unsigned int length = 0;
    // this assumes that the character array hasn't been manipulated to remove a terminating \0
    // '\0' resolves as false
    while(*str)
    {
        // increase the length integer
        length++;
        // move the pointer forward
        str++;
    }
    
    return length;
}

