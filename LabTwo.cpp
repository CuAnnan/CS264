/**
 * I am intentionally disregarding utf characters here because they're a nuisance to deal with in terms of replacement in this context.
 */
char* replace(char c, char p, const char* str)
{
    int len = length(str);// this provides an absolute upper bound for size of the output string
    char* out = new char[len];
    
    for(int i = 0; i < len; i++)
    {
        out[i] = *str == c?p:*str;
        *str++;
    }
    out[len] = '\0';
    return out;
}

