/**
 * I am assuming for the point of this question that we're not supposed to just
 * while ((*src++ = *from++)!='\0') which works.
 * Having spoken with Hao about this in lecture, we can disregard the NULL requirement
 * and just assume that there is sufficient space because "size" is not a meaningful keyword
 * in terms of a pointer, it will always just be the size of the type.
 */
char* copy(char* src, const char* test)
{
    int len2 = length(test);
    // treating the char pointers as arrays for simplicity of reading and comprehension
    for(int i = 0; i < len2; i++)
    {
        src[i] = test[i];
    }
    // making sure to add a terminator to the end
    src[len2] = '\0';
    return src;
}

/**
 * A quick method to compare two strings, we use this in a bunch of places
 */
bool strMatch(const char* str1, const char* str2)
{
    int strLen1 = length(str1);
    if(strLen1 != length(str2))
    {
        // if they're different lengths, they can't be the same strings
        return false;
    }

    for(int i = 0; i < strLen1; i++)
    {
        if(*str1 != *str2)
        {
            // if, at any point, the characters disagree, it's not the same string
            return false;
        }
        str1++;
        str2++;
    }
    // but we get here, so it is.
    return true;
}

