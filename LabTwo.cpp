/**
 * This more or less replicates length's functionality but as a side effect.
 * Length could be implemented as an function that opaquely maps length(str) to indexOf('\0', str)
 */
int indexOf(char c, const char* str)
{
    bool lfc = c == '\0';
    int i = 0;
    while((*str != '\0'))
    {
        if(*str == c)
        {
            return i;
        }
        str++;
        i++; 
    }

    return lfc?i:-1;
}

